import {createRequire} from 'node:module';
import path from 'node:path';
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const root=fileURLToPath(new URL('..',import.meta.url));
const out=path.join(root,'.qa');await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const checks=[];
await page.goto(process.env.TEST_URL||'http://127.0.0.1:4173');await page.waitForFunction(()=>window.tradeExplorer);
await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
checks.push({name:'initial',charts:await page.locator('.chart svg').count()});
for(const [topic,view]of [['composition','composition'],['products','trend'],['partners','composition'],['prices','trend'],['services','composition'],['investment','trend'],['economy','trend'],['workbench','trend'],['workbench','scatter'],['workbench','table']]){
  await page.locator(`[data-topic="${topic}"]`).click();
  await page.locator(`[data-view="${view}"]`).click();
  await page.waitForFunction(()=>!document.querySelector('#results')?.textContent.includes('Loading'));
  checks.push({name:topic+'-'+view,charts:await page.locator('.chart svg').count(),rows:await page.evaluate(()=>window.tradeExplorer.getRows().length),empty:await page.locator('#results .empty-state').allTextContents()});
}
await page.evaluate(async()=>window.tradeExplorer.setState({topic:'workbench',view:'trend',language:'zh'}));
checks.push({name:'english-only',lang:await page.locator('html').getAttribute('lang'),switches:await page.locator('#language-toggle').count()});
await page.screenshot({path:path.join(out,'workbench-en.png'),fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
checks.push({name:'mobile-overflow',width:await page.evaluate(()=>document.documentElement.scrollWidth),viewport:390});
await page.setViewportSize({width:1440,height:1000});
await page.evaluate(async()=>window.tradeExplorer.setState({topic:'composition',view:'composition',countries:window.tradeExplorer.data.catalog.countries.map(c=>c.id),year:2023}));
await page.screenshot({path:path.join(out,'all-country-composition.png'),fullPage:true});
checks.push({name:'20-country-composition',charts:await page.locator('.chart svg').count(),rows:await page.evaluate(()=>window.tradeExplorer.getRows().length)});
await page.evaluate(async()=>window.tradeExplorer.setState({topic:'products',view:'trend',countries:['KEN'],productCodes:['610910'],productMeasure:'unit',flow:'import',language:'en'}));
checks.push({name:'HS6-unit-value',rows:await page.evaluate(()=>window.tradeExplorer.getRows().length)});
const downloadPromise=page.waitForEvent('download');await page.locator('[data-action="download"]').click();const download=await downloadPromise;await download.saveAs(path.join(out,'sample-download.csv'));
checks.push({name:'CSV-download',filename:download.suggestedFilename()});
await page.evaluate(async()=>window.tradeExplorer.setState({topic:'sources'}));checks.push({name:'downloads',count:await page.locator('.file-link').count()});
console.log(JSON.stringify({checks,errors},null,2));
await fs.writeFile(path.join(out,'browser-results.json'),JSON.stringify({checks,errors},null,2));
await browser.close();
if(errors.length||checks.some(c=>c.name==='mobile-overflow'&&c.width>c.viewport))process.exitCode=1;
